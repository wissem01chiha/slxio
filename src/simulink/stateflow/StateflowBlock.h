#pragma once

#include "CommonPCH.h"

namespace slxio
{
    class StateflowChart;

    /**
     * A special Simulink block that stores state charts. There is
     * a one-to-one association between StateflowBlock and StateflowChart.
     * The sub blocks of this block are automatically generated by
     * Simulink.
     */
    class StateflowBlock
    {
    public:
        StateflowBlock() = default;
        StateflowBlock(StateflowChart& chart);

        /// Get a pointer to the StateflowChart which the blcok
        /// belong to
        std::shared_ptr<StateflowChart> GetChart();

        /// Remove this block from the StateflowChart
        void Remove();

    private:
        std::shared_ptr<StateflowChart> m_chart;
    };

}; // namespace slxio
